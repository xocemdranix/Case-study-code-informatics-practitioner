import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, classification_report

# 1. Simulasi Dataset Berdasarkan Kasus PT Maju Bersama
data = {
    'credit_value': [500000, 1200000, 300000, 2500000, 800000, 150000, 3000000, 950000],
    'payment_method': [1, 2, 1, 3, 2, 1, 3, 2], # 1: Transfer Bank, 2: Giro, 3: Tempo Panjang
    'customer_history_late': [0, 1, 0, 1, 0, 0, 1, 0], # Riwayat keterlambatan sebelumnya (0: Tidak, 1: Ya)
    'late_payment': [0, 1, 0, 1, 0, 0, 1, 0] # Target: Apakah invoice terlambat >30 hari (0: Tidak, 1: Ya)
}

df = pd.DataFrame(data)

# 2. Menentukan Fitur (X) dan Target (y)
# Menghindari data leakage dengan tidak menyertakan variabel hasil akhir di masa depan
X = df[['credit_value', 'payment_method', 'customer_history_late']]
y = df['late_payment']

# 3. Membagi Data Menjadi Training dan Testing (75% training, 25% testing)
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.25, random_state=42)

# 4. Pemodelan Menggunakan Random Forest Classifier
model = RandomForestClassifier(random_state=42)
model.fit(X_train, y_train)

# 5. Evaluasi Model
y_pred = model.predict(X_test)

print("Akurasi Model:", accuracy_score(y_test, y_pred))
print("\nLaporan Klasifikasi:\n", classification_report(y_test, y_pred, zero_division=0))